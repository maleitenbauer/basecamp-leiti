-- Lifestyle > Fitness > Training (backend package/schema stay "logbook", like the other Lifestyle modules).

-- A workout plan: a named, ordered list of exercises ("Push day"). It can be linked to a routine, so finishing a
-- workout from the plan ticks that routine off for the day.
CREATE TABLE logbook.workout_plan (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint       NOT NULL REFERENCES core.app_user (id) ON DELETE CASCADE,
    name       varchar(200) NOT NULL,
    note       varchar(500),
    routine_id bigint       REFERENCES logbook.routine (id) ON DELETE SET NULL,
    created_at timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX workout_plan_user_idx ON logbook.workout_plan (user_id, id);

CREATE TABLE logbook.workout_plan_exercise (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id      bigint           NOT NULL REFERENCES logbook.workout_plan (id) ON DELETE CASCADE,
    sort_order   integer          NOT NULL,
    name         varchar(200)     NOT NULL,
    sets         integer          NOT NULL CHECK (sets BETWEEN 1 AND 20),
    reps         integer          NOT NULL CHECK (reps BETWEEN 1 AND 200),
    weight_kg    double precision CHECK (weight_kg BETWEEN 0 AND 1000),
    rest_seconds integer          CHECK (rest_seconds BETWEEN 0 AND 900),
    note         varchar(300)
);

CREATE INDEX workout_plan_exercise_plan_idx ON logbook.workout_plan_exercise (plan_id, sort_order);

-- One time at the gym. finished_at is null while it is running; ended_by says whether the user finished it or the
-- automatic cut-off did. At most one running workout per user. name is a snapshot of the plan's name, so renaming or
-- deleting a plan never rewrites history; `day` is the calendar day as the user saw it when starting.
CREATE TABLE logbook.workout_session (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL REFERENCES core.app_user (id) ON DELETE CASCADE,
    plan_id     bigint       REFERENCES logbook.workout_plan (id) ON DELETE SET NULL,
    name        varchar(200) NOT NULL,
    day         date         NOT NULL,
    started_at  timestamptz  NOT NULL,
    finished_at timestamptz,
    ended_by    varchar(10)  CHECK (ended_by IN ('MANUAL', 'AUTO')),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT workout_session_finish_chk CHECK ((finished_at IS NULL) = (ended_by IS NULL))
);

CREATE UNIQUE INDEX workout_session_one_running_uq ON logbook.workout_session (user_id) WHERE finished_at IS NULL;
CREATE INDEX workout_session_user_day_idx ON logbook.workout_session (user_id, day);

-- The exercises of one workout: copied from the plan when it starts (so later plan edits don't change history), or
-- added on the spot. name_key is the lower-cased name, which is how "last time" and personal bests find an exercise.
CREATE TABLE logbook.workout_exercise (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint           NOT NULL REFERENCES core.app_user (id) ON DELETE CASCADE,
    session_id        bigint           NOT NULL REFERENCES logbook.workout_session (id) ON DELETE CASCADE,
    sort_order        integer          NOT NULL,
    name              varchar(200)     NOT NULL,
    name_key          varchar(200)     NOT NULL,
    target_sets       integer          CHECK (target_sets BETWEEN 1 AND 20),
    target_reps       integer          CHECK (target_reps BETWEEN 1 AND 200),
    target_weight_kg  double precision CHECK (target_weight_kg BETWEEN 0 AND 1000),
    rest_seconds      integer          CHECK (rest_seconds BETWEEN 0 AND 900)
);

CREATE INDEX workout_exercise_session_idx ON logbook.workout_exercise (session_id, sort_order);
CREATE INDEX workout_exercise_user_name_idx ON logbook.workout_exercise (user_id, name_key);

-- A set that was actually done. No weight means bodyweight.
CREATE TABLE logbook.workout_set (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint           NOT NULL REFERENCES core.app_user (id) ON DELETE CASCADE,
    exercise_id bigint           NOT NULL REFERENCES logbook.workout_exercise (id) ON DELETE CASCADE,
    reps        integer          NOT NULL CHECK (reps BETWEEN 1 AND 500),
    weight_kg   double precision CHECK (weight_kg BETWEEN 0 AND 1000),
    done_at     timestamptz      NOT NULL,
    created_at  timestamptz      NOT NULL DEFAULT now()
);

CREATE INDEX workout_set_exercise_idx ON logbook.workout_set (exercise_id, id);
